/**
 * Build output contract (design D5: TypeScript + tsdown, replacing build.mjs):
 *   - `lib/index.js` is the host half: one ESM module per source file emitted by
 *     `tsc -p tsconfig.build.json` (0.2 adds host/layer-store.js), entry exports
 *     name/inject/apply;
 *   - `lib/client.js` is one single-file `window.__ModuleLoader__.load`
 *     envelope emitted by tsdown whose factory requires only `react` and `zod`
 *     (no relative require), carries the inlined contract/token estimator, and
 *     returns the cordis plugin object with name/inject/apply.
 *
 * These are build-output assertions: they read the shipped lib artifacts, never
 * the sources, and they pin the artifact shape the platform loads.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';
import { loadZod } from './_zod.mjs';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const LIB = join(ROOT, 'lib');
const host = await readFile(join(LIB, 'index.js'), 'utf8');
const client = await readFile(join(LIB, 'client.js'), 'utf8');

test('bundle: lib/ contains the host entry and the client bundle', async () => {
  for (const relativePath of ['index.js', 'contract.js', 'host/store.js', 'host/layers.js', 'host/layer-store.js', 'host/service.js', 'host/typert.js', 'shared/tokens.js', 'client.js']) {
    const info = await stat(join(LIB, relativePath));
    assert.equal(info.isFile(), true, 'lib/' + relativePath + ' must exist');
  }
});

test('bundle: lib/index.js is the host ESM entry with name/inject/apply exports', () => {
  assert.match(host, /^export const name = 'dsh-prompt-library';/mu);
  assert.match(host, /^export const inject = \['typert', 'systemPrompt'\];/mu);
  assert.match(host, /^export function apply\(ctx\) \{/mu);
  assert.match(host, /^export function resolveSectionOrder\(/mu);
  // The host half is compiled ESM, never a CommonJS shim.
  assert.equal(/\brequire\(/u.test(host), false, 'the host half must be ESM, not CommonJS');
  assert.equal(/\bmodule\.exports\b/u.test(host), false, 'the host half must not define module.exports');
  assert.match(host, /^import\s/mu);
});

test('bundle: the client bundle is one ModuleLoader envelope requiring only react + zod', () => {
  assert.match(client, /^\/\/ dsh-prompt-library client bundle - generated by tsdown/u);
  assert.ok(client.includes('window.__ModuleLoader__.load({'), 'the envelope opener must be present');
  assert.equal(client.split('window.__ModuleLoader__.load(').length - 1, 1, 'lib/client.js must be exactly one bundle envelope');
  // Quote style is the bundler's business (the banner is printer-normalized), so
  // the shape is matched, not a literal.
  assert.match(client, /id:\s*["']dsh-prompt-library["']/u, 'the envelope must name the plugin');
  assert.match(client, /factory:\s*\(require\)\s*=>\s*\{/u, 'the envelope must expose the factory');
  assert.ok(client.trimEnd().endsWith('});'), 'the envelope must close');
  const ids = [...client.matchAll(/require\((['"])([^'"]+)\1\)/gu)].map((match) => match[2]).sort();
  assert.deepEqual(ids, ['react', 'zod'], 'the only runtime externals are react and zod');
  assert.equal(/require\(\s*['"]\.{1,2}\//u.test(client), false, 'no relative require at runtime');
  assert.equal(/^import\s/mu.test(client), false, 'the bundle must not keep ESM imports');
  assert.equal(/^export\s/mu.test(client), false, 'the bundle must not keep ESM exports');
  assert.match(client, /^\s*exports\.(?:name|inject|apply) = /mu, 'the factory must export the cordis plugin object');
});

test('bundle: the contract and the token estimator are inlined once (no relative require)', () => {
  assert.equal(client.includes('function defineContract(z) {'), true, 'the contract factory must be inlined');
  assert.equal(client.includes('function estimateTokens(text) {'), true, 'the token estimator must be inlined');
  assert.match(client, /const contract = defineContract\(/u, 'the bundle must bind one contract instance');
  assert.equal(client.split('function defineContract(z) {').length - 1, 1);
  assert.equal(client.split('function estimateTokens(text) {').length - 1, 1);
  assert.equal(/require\(\s*['"]\.{1,2}\//u.test(client), false);
});

test('bundle: the factory evaluates and returns the cordis plugin object', async () => {
  const z = await loadZod();
  let registered;
  const sandbox = {
    window: { __ModuleLoader__: { load(spec) { registered = spec; } } },
    console
  };
  runInNewContext(client, sandbox, { filename: 'lib/client.js' });
  assert.ok(registered, 'the bundle must call window.__ModuleLoader__.load');
  assert.equal(registered.id, 'dsh-prompt-library');
  assert.equal(typeof registered.factory, 'function');
  const requires = [];
  const exported = registered.factory((id) => {
    requires.push(id);
    if (id === 'react') return {};
    if (id === 'zod') return { z };
    throw new Error('unexpected require: ' + id);
  });
  assert.deepEqual([...requires].sort(), ['react', 'zod'], 'the factory requires exactly react and zod, nothing relative');
  assert.equal(exported.name, 'dsh-prompt-library');
  // The array was created in the vm realm; copy it into this realm before comparing.
  assert.deepEqual([...exported.inject], ['inputTriggers', 'sessions', 'connection', 'remote', 'slots', 'locale']);
  assert.equal(typeof exported.apply, 'function');
  assert.equal(exported.apply.length, 1);
});
